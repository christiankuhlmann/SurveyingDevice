    cal_mag_mags = [norm(cal_mag[:, i]) for i in range(20)]
    
    print(f"\nRaw magnetometer magnitudes: mean={np.mean(raw_mag_mags):.6f}, std={np.std(raw_mag_mags):.6f}")
    print(f"Calibrated magnetometer magnitudes: mean={np.mean(cal_mag_mags):.6f}, std={np.std(cal_mag_mags):.6f}")
    
