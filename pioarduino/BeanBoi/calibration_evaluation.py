def analyze_calibration_data():
    """Comprehensive analysis of calibration data quality"""
    
    print("=" * 80)
    print("CAVE SURVEYING DEVICE - CALIBRATION DATA EVALUATION")
    print("=" * 80)
    
    # Convert to numpy arrays for analysis
    Ra_static = np.array(calibration_data["Ra_static"])
    ba_static = np.array(calibration_data["ba_static"])
    Rm_static = np.array(calibration_data["Rm_static"])
    bm_static = np.array(calibration_data["bm_static"])
    Ra_laser = np.array(calibration_data["Ra_laser"])
    Rm_laser = np.array(calibration_data["Rm_laser"])
    Rm_align = np.array(calibration_data["Rm_align"])
    
    static_acc_samples = np.array(calibration_data["static_acc_samples"])
    static_mag_samples = np.array(calibration_data["static_mag_samples"])
    laser_acc_samples = np.array(calibration_data["laser_acc_samples"])
    laser_mag_samples = np.array(calibration_data["laser_mag_samples"])
    
    print("\n1. STATIC ACCELEROMETER CALIBRATION ANALYSIS")
    print("-" * 50)
    
    # Check accelerometer calibration matrix properties
    det_Ra = det(Ra_static)
    print(f"Ra_static determinant: {det_Ra:.6f} (should be ~1.0)")
    
    # Check if Ra is close to identity (good calibration means small corrections)
    Ra_error = Ra_static - np.eye(3)
    max_off_diag = np.max(np.abs(Ra_error[np.triu_indices(3, k=1)]))
    diag_error = np.abs(np.diag(Ra_error))
    print(f"Max off-diagonal error: {max_off_diag:.6f} (should be <0.01)")
    print(f"Diagonal errors: [{diag_error[0]:.6f}, {diag_error[1]:.6f}, {diag_error[2]:.6f}]")
    
    # Bias analysis
    bias_magnitude = norm(ba_static)
    print(f"Accelerometer bias magnitude: {bias_magnitude:.6f} g")
    print(f"Accelerometer bias: [{ba_static[0]:.6f}, {ba_static[1]:.6f}, {ba_static[2]:.6f}] g")
    
    # Analyze static accelerometer sample quality
    print(f"\nStatic accelerometer samples shape: {static_acc_samples.shape}")
    for i, axis in enumerate(['X', 'Y', 'Z']):
        samples = static_acc_samples[i]
        print(f"  {axis}-axis: mean={np.mean(samples):.6f}, std={np.std(samples):.6f}, range={np.ptp(samples):.6f}")
    
    # Check if we have the expected 6 orientations (plus laser calibration)
    n_samples_per_orientation = len(static_acc_samples[0]) // 8  # Assuming 6 static + 2 laser
    print(f"Samples per orientation: ~{n_samples_per_orientation}")
    
    print("\n2. STATIC MAGNETOMETER CALIBRATION ANALYSIS")
    print("-" * 50)
    
    # Check magnetometer calibration matrix
    det_Rm = det(Rm_static)
    print(f"Rm_static determinant: {det_Rm:.6f}")
    
    # Magnetometer calibration is more complex - check eigenvalues for ellipsoid correction
    eigenvals = np.linalg.eigvals(Rm_static)
    print(f"Rm_static eigenvalues: [{eigenvals[0]:.6f}, {eigenvals[1]:.6f}, {eigenvals[2]:.6f}]")
    
    # Check condition number
    cond_num = np.linalg.cond(Rm_static)
    print(f"Rm_static condition number: {cond_num:.3f} (lower is better)")
    
    # Magnetometer bias
    mag_bias_magnitude = norm(bm_static)
    print(f"Magnetometer bias magnitude: {mag_bias_magnitude:.6f}")
    print(f"Magnetometer bias: [{bm_static[0]:.6f}, {bm_static[1]:.6f}, {bm_static[2]:.6f}]")
    
    # Analyze static magnetometer sample quality
    print(f"\nStatic magnetometer samples shape: {static_mag_samples.shape}")
    for i, axis in enumerate(['X', 'Y', 'Z']):
        samples = static_mag_samples[i]
        print(f"  {axis}-axis: mean={np.mean(samples):.6f}, std={np.std(samples):.6f}, range={np.ptp(samples):.6f}")
    
    print("\n3. LASER CALIBRATION ANALYSIS")
    print("-" * 50)
    
    # Check laser calibration matrices
    det_Ra_laser = det(Ra_laser)
    det_Rm_laser = det(Rm_laser)
    print(f"Ra_laser determinant: {det_Ra_laser:.6f} (should be ~±1.0)")
    print(f"Rm_laser determinant: {det_Rm_laser:.6f} (should be ~±1.0)")
    
    # Check if laser matrices are proper rotations
    Ra_orth_error = norm(Ra_laser @ Ra_laser.T - np.eye(3))
    Rm_orth_error = norm(Rm_laser @ Rm_laser.T - np.eye(3))
    print(f"Ra_laser orthogonality error: {Ra_orth_error:.8f} (should be ~0)")
    print(f"Rm_laser orthogonality error: {Rm_orth_error:.8f} (should be ~0)")
    
    # Analyze laser sample quality
    print(f"\nLaser accelerometer samples shape: {laser_acc_samples.shape}")
    print(f"Laser magnetometer samples shape: {laser_mag_samples.shape}")
    
    # Check sample magnitudes during laser calibration
    for i in range(laser_acc_samples.shape[1]):
        acc_mag = norm(laser_acc_samples[:, i])
        mag_mag = norm(laser_mag_samples[:, i])
        print(f"  Sample {i+1}: |acc|={acc_mag:.6f} g, |mag|={mag_mag:.6f}")
    
    print("\n4. ALIGNMENT MATRIX ANALYSIS")
    print("-" * 50)
    
    # Check alignment matrix properties
    det_Rm_align = det(Rm_align)
    print(f"Rm_align determinant: {det_Rm_align:.6f} (should be ~±1.0)")
    
    Rm_align_orth_error = norm(Rm_align @ Rm_align.T - np.eye(3))
    print(f"Rm_align orthogonality error: {Rm_align_orth_error:.8f} (should be ~0)")
    
    # Extract rotation angles from alignment matrix
    def rotation_matrix_to_euler_zyx(R):
        """Convert rotation matrix to ZYX Euler angles (yaw, pitch, roll)"""
        sy = np.sqrt(R[0,0]**2 + R[1,0]**2)
        singular = sy < 1e-6
        
        if not singular:
            x = np.arctan2(R[2,1], R[2,2])  # roll
            y = np.arctan2(-R[2,0], sy)     # pitch
            z = np.arctan2(R[1,0], R[0,0])  # yaw
        else:
            x = np.arctan2(-R[1,2], R[1,1])
            y = np.arctan2(-R[2,0], sy)
            z = 0
        
        return np.degrees([z, y, x])  # yaw, pitch, roll in degrees
    
    euler_angles = rotation_matrix_to_euler_zyx(Rm_align)
    print(f"Alignment angles (yaw, pitch, roll): [{euler_angles[0]:.2f}°, {euler_angles[1]:.2f}°, {euler_angles[2]:.2f}°]")
    
